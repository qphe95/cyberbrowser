// gen_psl.js - builds src/proc/psl_data.h from the Public Suffix List.
//   node tools/gen_psl.js third_party/psl/public_suffix_list.dat src/proc/psl_data.h
// Rules become three sorted tables of ASCII (punycode) names: plain rules,
// wildcard rules "*.x" (stored as "x") and exception rules "!x" (stored as
// "x").  site.c binary-searches them, comparing bytes, so the sort here is
// by byte value.
const fs = require('fs');
const url = require('url');

const [src, dst] = process.argv.slice(2);
const text = fs.readFileSync(src, 'utf8');
const version = (text.match(/^\/\/ VERSION: (.*)$/m) || [, 'unknown'])[1].trim();
const plain = new Set(), wild = new Set(), exc = new Set();

for (let line of text.split('\n')) {
  line = line.trim().split(/\s/)[0];
  if (!line || line.startsWith('//')) continue;
  let set = plain;
  if (line.startsWith('!')) { set = exc; line = line.slice(1); }
  else if (line.startsWith('*.')) { set = wild; line = line.slice(2); }
  if (line.includes('*')) throw new Error('wildcard not at the left: ' + line);
  const ascii = url.domainToASCII(line);
  if (!ascii || !/^[a-z0-9-]+(\.[a-z0-9-]+)*$/.test(ascii)) throw new Error('bad rule: ' + line);
  set.add(ascii);
}

const byBytes = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
function table(name, set) {
  const names = [...set].sort(byBytes);
  const offs = [];
  let blob = '', lines = [];
  for (const n of names) {
    offs.push(blob.length);
    blob += n + '\0';
    lines.push('    "' + n + '\\0"');
  }
  return `static const char ${name}_STR[] =\n${lines.join('\n')};\n` +
    `static const uint32_t ${name}_OFF[${names.length}] = {\n` +
    offs.map((o, i) => (i % 12 === 0 ? '    ' : '') + o + ',' + (i % 12 === 11 ? '\n' : ' ')).join('').trimEnd() + '\n};\n' +
    `#define ${name}_N ${names.length}u\n`;
}

const out = `/* psl_data.h - the Public Suffix List as tables, for site.c only.
 * Generated by tools/gen_psl.js from third_party/psl/public_suffix_list.dat
 * (version ${version}); do not edit.  The list is under the Mozilla Public
 * License 2.0 (https://mozilla.org/MPL/2.0/). */
#ifndef PSL_DATA_H
#define PSL_DATA_H
#define PSL_VERSION "${version}"

/* Rules "x": x is a public suffix. */
${table('PSL_PLAIN', plain)}
/* Rules "*.x": every child of x is a public suffix. */
${table('PSL_WILD', wild)}
/* Rules "!x": x is not a public suffix, though a wildcard covers it. */
${table('PSL_EXC', exc)}
#endif
`;
fs.writeFileSync(dst, out);
console.log(`${version}: ${plain.size} plain, ${wild.size} wildcard, ${exc.size} exception rules`);
