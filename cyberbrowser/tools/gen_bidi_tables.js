// Generates src/bidi_tables.h: the Unicode Bidi_Class of every code point,
// mirroring pairs and paired brackets, for src/bidi.c (UAX #9).
// node tools/gen_bidi_tables.js <ucd dir> out.h
// <ucd dir> holds DerivedBidiClass.txt, BidiMirroring.txt and BidiBrackets.txt
// from https://www.unicode.org/Public/UCD/latest/ucd/ (the first in extracted/).
const fs = require('fs');
const path = require('path');
const [dir, outFile] = process.argv.slice(2);
const read = f => fs.readFileSync(path.join(dir, f), 'utf8');

const NAMES = { Left_To_Right: 'L', Right_To_Left: 'R', Arabic_Letter: 'AL', European_Terminator: 'ET' };
const CLASSES = ['L', 'R', 'AL', 'EN', 'ES', 'ET', 'AN', 'CS', 'NSM', 'BN', 'B', 'S', 'WS', 'ON',
                 'LRE', 'LRO', 'RLE', 'RLO', 'PDF', 'LRI', 'RLI', 'FSI', 'PDI'];
const cls = new Uint8Array(0x110000);   // index into CLASSES; 0 = L

// The @missing defaults first (in file order, later ones narrower), then the
// listed values over them.
const derived = read('DerivedBidiClass.txt');
const version = (derived.match(/DerivedBidiClass-([\d.]+)\.txt/) || [])[1] || '?';
for (const m of derived.matchAll(/^# @missing: ([0-9A-F]+)\.\.([0-9A-F]+); (\w+)/gm)) {
    const c = CLASSES.indexOf(NAMES[m[3]]);
    if (c < 0) throw new Error('@missing value ' + m[3]);
    cls.fill(c, parseInt(m[1], 16), parseInt(m[2], 16) + 1);
}
for (const line of derived.split('\n')) {
    const m = line.match(/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)/);
    if (!m) continue;
    const c = CLASSES.indexOf(m[3]);
    if (c < 0) throw new Error('class ' + m[3]);
    cls.fill(c, parseInt(m[1], 16), parseInt(m[2] || m[1], 16) + 1);
}

// Ranges of equal class, leaving out L (the default the lookup falls back to).
const ranges = [];
for (let cp = 0; cp < 0x110000;) {
    let e = cp;
    while (e + 1 < 0x110000 && cls[e + 1] === cls[cp]) e++;
    if (cls[cp] !== 0) ranges.push([cp, e, cls[cp]]);
    cp = e + 1;
}

const mirror = [];
for (const line of read('BidiMirroring.txt').split('\n')) {
    const m = line.match(/^([0-9A-F]+);\s*([0-9A-F]+)/);
    if (m) mirror.push([parseInt(m[1], 16), parseInt(m[2], 16)]);
}
const brackets = [];
for (const line of read('BidiBrackets.txt').split('\n')) {
    const m = line.match(/^([0-9A-F]+);\s*([0-9A-F]+);\s*([oc])/);
    if (m) brackets.push([parseInt(m[1], 16), parseInt(m[2], 16), m[3] === 'o' ? 1 : 2]);
}

const hex = n => '0x' + n.toString(16).toUpperCase();
function rows(list, fmt, per) {
    let o = '';
    for (let i = 0; i < list.length; i += per) o += '    ' + list.slice(i, i + per).map(fmt).join(', ') + ',\n';
    return o;
}
let out = `/* Generated by tools/gen_bidi_tables.js from the Unicode ${version} data files
 * DerivedBidiClass.txt, BidiMirroring.txt and BidiBrackets.txt.  Do not edit. */
/* Code points whose Bidi_Class is not L, as ranges sorted by start. */
typedef struct { unsigned int lo, hi; unsigned char cls; } BidiRange;
static const BidiRange k_bidi_ranges[${ranges.length}] = {
${rows(ranges, ([a, b, c]) => `{ ${hex(a)}, ${hex(b)}, BIDI_${CLASSES[c]} }`, 3)}};
/* Bidi_Mirroring_Glyph, sorted by code point. */
typedef struct { unsigned int cp, to; } BidiPair;
static const BidiPair k_bidi_mirror[${mirror.length}] = {
${rows(mirror, ([a, b]) => `{ ${hex(a)}, ${hex(b)} }`, 6)}};
/* Bidi_Paired_Bracket and its type (1 open, 2 close), sorted by code point. */
typedef struct { unsigned int cp, pair; unsigned char type; } BidiBracket;
static const BidiBracket k_bidi_brackets[${brackets.length}] = {
${rows(brackets, ([a, b, t]) => `{ ${hex(a)}, ${hex(b)}, ${t} }`, 4)}};
`;
fs.writeFileSync(outFile, out);
console.log('unicode', version, 'ranges', ranges.length, 'mirror', mirror.length, 'brackets', brackets.length);
