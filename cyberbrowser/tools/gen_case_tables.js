// Generates src/case_tables.h: Unicode full case mappings (uppercase and
// lowercase, from JavaScript's String toUpperCase / toLowerCase of each code
// point alone) for CSS text-transform.  node tools/gen_case_tables.js out.h
const fs = require('fs');
const up = [], low = [];
for (let cp = 0; cp <= 0x10FFFF; cp++) {
    if (cp >= 0xD800 && cp <= 0xDFFF) continue;
    const s = String.fromCodePoint(cp);
    const u = s.toUpperCase(), l = s.toLowerCase();
    if (u !== s) up.push([cp, u]);
    if (l !== s) low.push([cp, l]);
}
function cstr(s) {
    return '"' + [...Buffer.from(s, 'utf8')].map(b => '\\x' + b.toString(16).padStart(2, '0')).join('') + '"';
}
function table(name, rows) {
    let o = `static const CaseMap ${name}[${rows.length}] = {\n`;
    for (let i = 0; i < rows.length; i += 4)
        o += '    ' + rows.slice(i, i + 4).map(([cp, s]) => `{ 0x${cp.toString(16).toUpperCase()}, ${cstr(s)} }`).join(', ') + ',\n';
    return o + '};\n';
}
let out = '/* Generated by tools/gen_case_tables.js (Unicode full case mappings of\n' +
          ' * single code points, sorted by code point).  Do not edit. */\n' +
          'typedef struct { unsigned int cp; const char *to; } CaseMap;\n';
out += table('k_case_upper', up) + table('k_case_lower', low);
fs.writeFileSync(process.argv[2], out);
console.log('upper', up.length, 'lower', low.length);
