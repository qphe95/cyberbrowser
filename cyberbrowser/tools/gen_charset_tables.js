// Generates src/charset_tables.h: the WHATWG single-byte encodings' tables
// (bytes 0x80..0xFF to code points, 0: none) and the Big5 decoder's index
// (pointer to code point), from Node's TextDecoder.
//   node tools/gen_charset_tables.js src/charset_tables.h
const fs = require('fs');
const single = ['IBM866', 'ISO-8859-2', 'ISO-8859-3', 'ISO-8859-4', 'ISO-8859-5', 'ISO-8859-6', 'ISO-8859-7',
                'ISO-8859-8', 'ISO-8859-8-I', 'ISO-8859-10', 'ISO-8859-13', 'ISO-8859-14', 'ISO-8859-15', 'ISO-8859-16',
                'KOI8-R', 'KOI8-U', 'macintosh', 'windows-874', 'windows-1250', 'windows-1251', 'windows-1252',
                'windows-1253', 'windows-1254', 'windows-1255', 'windows-1256', 'windows-1257', 'windows-1258',
                'x-mac-cyrillic'];
let out = '/* Generated by tools/gen_charset_tables.js from the WHATWG encodings (Node\'s\n' +
          ' * TextDecoder).  Do not edit. */\n';
out += 'typedef struct { const char *name; unsigned short hi[128]; } SingleByteTable;\n';
out += 'static const SingleByteTable k_single_byte[' + single.length + '] = {\n';
for (const name of single) {
    const d = new TextDecoder(name);
    const hi = [];
    for (let b = 0x80; b <= 0xFF; b++) {
        const s = d.decode(new Uint8Array([b]));
        const cp = s.codePointAt(0);
        hi.push(s.length === 1 && cp !== 0xFFFD ? cp : 0);
    }
    out += `    { "${name}", {\n`;
    for (let i = 0; i < 128; i += 16)
        out += '        ' + hi.slice(i, i + 16).map(v => '0x' + v.toString(16).toUpperCase().padStart(4, '0')).join(', ') + ',\n';
    out += '    } },\n';
}
out += '};\n';

// Big5: pointer = (lead - 0x81) * 157 + (trail - (trail < 0x7F ? 0x40 : 0x62)).
const big5 = new TextDecoder('big5');
const N = 126 * 157;
const tab = new Array(N).fill(0);
const pairs = [];
for (let p = 0; p < N; p++) {
    const lead = Math.floor(p / 157) + 0x81, off = p % 157;
    const trail = off + (off < 0x3F ? 0x40 : 0x62);
    const s = big5.decode(new Uint8Array([lead, trail]));
    const cps = [...s].map(c => c.codePointAt(0));
    if (cps.length === 1 && cps[0] !== 0xFFFD) tab[p] = cps[0];
    else if (cps.length === 2 && !cps.includes(0xFFFD)) pairs.push([p, cps[0], cps[1]]);
}
out += '/* Big5 two-byte pointers to code points (0: none); the few that decode to\n' +
       ' * two code points are in k_big5_pairs. */\n';
out += `static const unsigned int k_big5_index[${N}] = {\n`;
for (let i = 0; i < N; i += 10)
    out += '    ' + tab.slice(i, i + 10).map(v => '0x' + v.toString(16).toUpperCase()).join(', ') + ',\n';
out += '};\n';
/* (a pointer no table has when there are none: C has no empty arrays) */
if (!pairs.length) pairs.push([0xFFFFFFFF, 0, 0]);
out += `static const unsigned int k_big5_pairs[${pairs.length}][3] = {\n`;
for (const [p, a, b] of pairs) out += `    { 0x${p.toString(16).toUpperCase()}, 0x${a.toString(16).toUpperCase()}, 0x${b.toString(16).toUpperCase()} },\n`;
out += '};\n';
fs.writeFileSync(process.argv[2], out);
console.log('single-byte', single.length, 'big5 mapped', tab.filter(v => v).length, 'pairs', pairs.length);
