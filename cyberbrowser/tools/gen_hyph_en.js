// node tools/gen_hyph_en.js <hyph_en_US.dic> : writes src/hyph_en_data.inc, the US English
// hyphenation patterns (Liang's, as the Hyphen library's dictionary has them) as one C string.
const fs = require('fs'), path = require('path');
const dic = process.argv[2];
if (!dic) { console.error('usage: gen_hyph_en.js <hyph_en_US.dic>'); process.exit(1); }
const lines = fs.readFileSync(dic, 'utf8').split(/\r?\n/);
// (only plain patterns: the header's keywords have capitals, the Hyphen extensions a '/')
const pats = lines.filter(l => /^[a-z.0-9]+$/.test(l) && /[a-z]/.test(l));
const head = `/* Generated by tools/gen_hyph_en.js from hyph_en_US.dic.  Do not edit.
 *
 * Based on the plain TeX hyphenation table (hyphen.tex: "Unlimited copying and
 * redistribution of this file are permitted as long as this file is not modified.
 * Modifications are permitted, but only if the resulting file is not named hyphen.tex.")
 * and the TUGboat hyphenation exception log ("Copyright 2007 TeX Users Group. You may
 * freely use, modify and/or distribute this file."), converted by Laszlo Nemeth
 * for the Hyphen library (BSD-style: unlimited copying, redistribution and modification
 * permitted with this copyright and license information). */
`;
let out = head + 'static const char k_hyph_en[] =\n';
for (let i = 0; i < pats.length; i += 12) out += '"' + pats.slice(i, i + 12).join(' ') + ' "\n';
out += ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'hyph_en_data.inc'), out);
console.log(pats.length, 'patterns,', out.length, 'bytes');
