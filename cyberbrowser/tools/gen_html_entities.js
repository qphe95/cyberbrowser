// node tools/gen_html_entities.js <entities.json> : writes src/html_entities.inc, HTML's named
// character references sorted by name for a binary search.  entities.json is the spec's list
// (https://html.spec.whatwg.org/entities.json; WPT keeps a copy under html/the-xhtml-syntax).
const fs = require('fs'), path = require('path');
const json = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const byName = new Map();
for (const [key, v] of Object.entries(json)) {
    const semi = key.endsWith(';');
    const name = key.slice(1, semi ? -1 : undefined);
    const e = byName.get(name) || { cps: v.codepoints, legacy: false };
    if (!semi) e.legacy = true;   // (matches without its semicolon too)
    byName.set(name, e);
}
const names = [...byName.keys()].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
let out = '/* Generated by tools/gen_html_entities.js from the HTML standard\'s entities.json.  Do not edit. */\n';
out += 'static const struct { const char *name; uint32_t cp, cp2; unsigned char legacy; } k_html_entities[] = {\n';
for (const n of names) {
    const e = byName.get(n);
    out += `{"${n}",0x${e.cps[0].toString(16)},0x${(e.cps[1] || 0).toString(16)},${e.legacy ? 1 : 0}},\n`;
}
out += '};\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'html_entities.inc'), out);
// (how much longer than its source a reference's UTF-8 can be: the in-place decoder allows for it)
const u8 = c => (c < 0x80 ? 1 : c < 0x800 ? 2 : c < 0x10000 ? 3 : 4);
let worst = 0, worstName = '';
for (const n of names) {
    const e = byName.get(n);
    const grow = e.cps.reduce((s, c) => s + u8(c), 0) - (n.length + 1 + (e.legacy ? 0 : 1));
    if (grow > worst) { worst = grow; worstName = n; }
}
console.log(names.length, 'names; longest', Math.max(...names.map(n => n.length)), '; most growth', worst, worstName);
