// The interfaces (not mixins: their members folded into the interfaces that include them) and
// their regular attribute and operation names, as a JS literal the hoisting shim reads.
const fs = require('fs');
const ifaces = {}, mixins = {}, includes = [];
for (const f of process.argv.slice(2)) {
    const src = fs.readFileSync(f, 'utf8').replace(/\/\/.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, '');
    const re = /(?:\[([^\]]*)\]\s*)?(partial\s+)?interface\s+(mixin\s+)?(\w+)(?:\s*:\s*(\w+))?\s*\{([\s\S]*?)\n\};/g;
    let m;
    while ((m = re.exec(src))) {
        const name = m[4], body = m[6], mixin = !!m[3];
        const set = (mixin ? mixins : ifaces)[name] = (mixin ? mixins : ifaces)[name] || new Set();
        for (const line of body.split(';')) {
            if (/\bstatic\b|\bconst\b/.test(line)) continue;
            const a = line.match(/attribute\s+[\w<>?, ]+?\s+(\w+)\s*$/);
            const o = line.match(/^\s*(?:\[[^\]]*\]\s*)?[\w<>?(), ]+?\s+(\w+)\s*\(/);
            const mem = a ? a[1] : o ? o[1] : null;
            if (!mem || /^(getter|setter|deleter|stringifier|constructor|undefined)$/.test(mem)) continue;
            set.add(mem);
        }
    }
    for (const im of src.matchAll(/(\w+)\s+includes\s+(\w+)\s*;/g)) includes.push([im[1], im[2]]);
}
for (const [i, mx] of includes) if (ifaces[i] && mixins[mx]) for (const x of mixins[mx]) ifaces[i].add(x);
const out = {};
for (const k of Object.keys(ifaces).sort()) if (ifaces[k].size) out[k] = [...ifaces[k]];
process.stdout.write('/* generated by tools/gen_idl_members.js from html.idl: do not edit */\nvar __cyberIdlMembers = ' + JSON.stringify(out) + ';\n');
