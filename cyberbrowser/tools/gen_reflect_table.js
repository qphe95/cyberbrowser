// node tools/gen_reflect_table.js <wpt>/html/dom : writes src/browser/reflect_table.js, which
// IDL attributes of which HTML elements reflect which content attributes and how: the HTML
// standard's rules as web-platform-tests' elements-*.js list them.
const fs = require('fs'), path = require('path'), vm = require('vm');
const dir = process.argv[2];
const groups = [];
const ctx = { mergeElements: o => groups.push(o), extraTests: [] };
vm.createContext(ctx);
const files = fs.readdirSync(dir).filter(f => /^elements-.*\.js$/.test(f));
/* (the ARIA attributes: div's in that file, on every element in truth) */
for (const f of files) {
    const before = groups.length;
    vm.runInContext(fs.readFileSync(path.join(dir, f), 'utf8'), ctx);
    if (/aria/.test(f)) for (let g = before; g < groups.length; g++) groups[g] = { __aria: groups[g].div };
}
const table = {};
const kinds = new Set();
for (const group of groups) {
    for (const [tag, attrs] of Object.entries(group)) {
        const t = table[tag] = table[tag] || {};
        for (const [idl, ty] of Object.entries(attrs)) {
            const o = typeof ty === 'string' ? { type: ty } : JSON.parse(JSON.stringify(ty));
            if (typeof ty === 'object' && ty.type && typeof ty.type === 'object') o.type = ty.type;
            kinds.add(typeof o.type === 'string' ? o.type : JSON.stringify(o.type));
            t[idl] = o;
        }
    }
}
const out = '/* Generated by tools/gen_reflect_table.js from the lists in web-platform-tests html/dom. Do not edit. */\n' +
            'var __cyberReflectTable = ' + JSON.stringify(table) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'browser', 'reflect_table.js'), out);
console.log(files.join(' '), Object.keys(table).length, 'elements;', out.length, 'bytes;', [...kinds].join(', '));
