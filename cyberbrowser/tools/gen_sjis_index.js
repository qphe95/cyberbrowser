// Generates src/sjis_index.h: the WHATWG Shift_JIS decoder's two-byte table
// (pointer -> code point, 0: none), from Node's TextDecoder.
const fs = require('fs');
const d = new TextDecoder('shift_jis');
const N = 60 * 188;
const tab = new Array(N).fill(0);
for (let p = 0; p < N; p++) {
    const lead = Math.floor(p / 188), t = p % 188;
    const l = lead + (lead < 0x1F ? 0x81 : 0xC1);
    const b = t + (t < 0x3F ? 0x40 : 0x41);
    if (p >= 8836 && p <= 10715) continue;   /* (user-defined area: computed) */
    const s = d.decode(new Uint8Array([l, b]));
    const cps = [...s].map(c => c.codePointAt(0));
    if (cps.length === 1 && cps[0] !== 0xFFFD && cps[0] <= 0xFFFF) tab[p] = cps[0];
}
let out = '/* Generated by tools/gen_sjis_index.js from the WHATWG Shift_JIS decoder:\n' +
          ' * two-byte pointer ((lead - offset) * 188 + trail - offset) to code point,\n' +
          ' * 0 for none.  Do not edit. */\n' +
          'static const unsigned short k_sjis_index[' + N + '] = {\n';
for (let i = 0; i < N; i += 12)
    out += '    ' + tab.slice(i, i + 12).map(v => '0x' + v.toString(16).toUpperCase().padStart(4, '0')).join(', ') + ',\n';
out += '};\n';
fs.writeFileSync(process.argv[2], out);
console.log('mapped', tab.filter(v => v).length);
