#!/usr/bin/env node
// Steady-state JS benchmarks for the engine (JS_PERF_DESIGN.md section 4.3):
// JetStream's tests (Octane, the Web Tooling Benchmark and the rest of its
// plain-JS workloads) turned into one self-contained script each, which
// cyberbrowser runs through CYBER_PROBE_JS in a fresh process.
//
//   node tools/jsbench.js list <JetStream dir> [tag...]
//       the tests (all of them, or those with any of the tags: Octane, WTB, ...)
//   node tools/jsbench.js gen <JetStream dir> <out dir> <test...>
//       write <out dir>/<test>.js for each test
//
// JetStream's own driver (JetStreamDriver.js) assembles each test, so the
// files, preloads, iteration counts, deterministic Math.random and runner
// code are exactly what its command-line runner uses: the script it would
// evaluate in a fresh global is captured instead (ShellScripts.run) and
// written out with a prefix that stands in for the shell (top.currentResolve
// prints the iteration times; preloads become strings).  Tests that need
// WebAssembly, workers or modules are left out.
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const [cmd, jsDir, ...rest] = process.argv.slice(2);
if (!cmd || !jsDir) {
    console.error('usage: jsbench.js list <JetStream dir> [tag...] | gen <JetStream dir> <out dir> <test...>');
    process.exit(2);
}
if (cmd === 'gen' && rest[0])
    rest[0] = path.resolve(rest[0]);   /* before the chdir below */

// The shell API JetStream's command-line runner expects, enough to load its
// driver and read the tests' files (relative to the JetStream directory).
process.chdir(jsDir);
globalThis.readFile = f => fs.readFileSync(f, 'utf8');
globalThis.read = (f, mode) => mode === 'binary' ? new Uint8Array(fs.readFileSync(f)).buffer : fs.readFileSync(f, 'utf8');
globalThis.load = f => vm.runInThisContext(fs.readFileSync(f, 'utf8'), { filename: f });
globalThis.print = (...a) => console.log(...a);
globalThis.printErr = (...a) => console.error(...a);
globalThis.arguments = ['--dump-test-list'];
globalThis.scriptArgs = globalThis.arguments;
// cli.js with --dump-test-list loads the driver and prints the list: keep
// the driver, drop the printing.
const realLog = console.log;
console.log = () => {};
load('./cli.js');
console.log = realLog;

// Tests JetStream tags as plain JS.  WebAssembly, workers and module
// imports need more of a shell than CYBER_PROBE_JS gives.
const EXCLUDE_TAGS = new Set(['wasm', 'wasmeh', 'worker', 'workertests', 'wasm-jspi']);
const tagsOf = b => [...(b.tags || [])].map(t => t.toLowerCase());
function isPlainJS(b) {
    const tags = tagsOf(b);
    if (tags.some(t => EXCLUDE_TAGS.has(t)) || !tags.includes('js'))
        return false;
    if (b.constructor.name.includes('Wasm') || b.constructor.name.includes('Group'))
        return false;
    return (b.files || []).every(f => /\.(js|mjs)$/.test(f) && !/\.mjs$/.test(f));
}
const all = vm.runInThisContext('BENCHMARKS');

if (cmd === 'list') {
    const want = new Set(rest.map(t => t.toLowerCase()));
    for (const b of all) {
        if (!isPlainJS(b))
            continue;
        if (want.size && !tagsOf(b).some(t => want.has(t)))
            continue;
        realLog(`${b.name}\t${b.iterations}\t${tagsOf(b).join(',')}`);
    }
} else if (cmd === 'gen') {
    const [outDir, ...names] = rest;
    fs.mkdirSync(outDir, { recursive: true });
    const byName = new Map(all.map(b => [b.name.toLowerCase(), b]));
    const ShellScripts = vm.runInThisContext('ShellScripts');
    for (const name of names) {
        const b = byName.get(name.toLowerCase());
        if (!b || !isPlainJS(b)) {
            console.error(`no plain-JS test ${name}`);
            process.exitCode = 1;
            continue;
        }
        b.prefetchResourcesForShell();
        let captured = null;
        const realRun = ShellScripts.prototype.run;
        ShellScripts.prototype.run = function () { captured = this; return {}; };
        b.run().catch(() => {});      // assembles the scripts, then waits forever: dropped
        ShellScripts.prototype.run = realRun;
        if (!captured) {
            console.error(`${name}: the driver did not assemble it`);
            process.exitCode = 1;
            continue;
        }
        // Text resources as strings; binary ones (.wasm) as base64, decoded
        // to an Int8Array (what getBinary returns) when the script starts.
        const resources = {}, binaries = {};
        for (const [file, bytes] of Object.entries(captured.prefetchedResources)) {
            const buf = Buffer.from(bytes.buffer || bytes);
            if (/\.wasm$/.test(file))
                binaries[file] = buf.toString('base64');
            else
                resources[file] = buf.toString('utf8');
        }
        const prefix = `// ${b.name}: generated by tools/jsbench.js from JetStream
globalThis.print ??= (...a) => console.log(...a);
const __jsbenchOut = console.error.bind(console);   /* workloads may replace console's */
globalThis.top = {
    // One line per iteration: the console splits long lines.
    currentResolve(results) {
        for (const r of results) __jsbenchOut('JSBENCH-ITER ' + r);
        __jsbenchOut('JSBENCH-DONE ' + results.length);
    },
    currentReject(e) { __jsbenchOut('JSBENCH-ERROR ' + String(e) + ' ' + (e && e.stack || '')); },
};
globalThis.self = globalThis;
globalThis.ShellPrefetchedResources = ${JSON.stringify(resources)};
(function (b64) {
    const A = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/';
    for (const [file, s] of Object.entries(b64)) {
        const clean = s.replace(/=+$/, ''), out = new Int8Array(Math.floor(clean.length * 3 / 4));
        let bits = 0, n = 0, o = 0;
        for (let i = 0; i < clean.length; i++) {
            bits = (bits << 6) | A.indexOf(clean[i]); n += 6;
            if (n >= 8) { n -= 8; out[o++] = (bits >> n) & 255; }
        }
        ShellPrefetchedResources[file] = out;
    }
})(${JSON.stringify(binaries)});
globalThis.ShellTextDecoder = class { decode(s) { return typeof s === 'string' ? s : new TextDecoder().decode(s); } };
globalThis.read = (p) => { if (p in ShellPrefetchedResources) return ShellPrefetchedResources[p]; throw new Error('read: ' + p); };
`;
        // One script: the pieces share the global scope (their top-level
        // class and let declarations included), as each loadString's do.
        const body = captured.scripts.map(s => `\n;\n${s}\n`).join('');
        fs.writeFileSync(path.join(outDir, `${b.name}.js`), prefix + body);
        realLog(`${b.name}\t${b.iterations}`);
    }
}
